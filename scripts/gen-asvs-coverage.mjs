/**
 * Generates docs/reference/asvs-coverage.md plus the coverage snapshot.
 *
 * Joins the vendored ASVS 5.0 control inventory
 * (rules/catalogues/asvs-5.0-controls.yaml) against every ASVS-* reference
 * cited by the rule packs (loaded through the real engine in dist/, so
 * automatability values cannot drift from what the engine computes).
 * Controls nobody cites are listed as unassessed — explicitly not
 * "uncoverable": partial/uncoverable triage is future work, and the map
 * must not launder "not yet judged" into a verdict.
 *
 * Like the other generators, output is a committed build artifact: CI
 * regenerates and fails on any diff, and the snapshot makes silent
 * coverage drops a red build.
 *
 * Usage:
 *   node scripts/gen-asvs-coverage.mjs          # regenerate doc + snapshot
 *   node scripts/gen-asvs-coverage.mjs --check  # exit 1 if either is stale
 * Requires `dist/` (run `pnpm run build` first).
 */
import fs from 'node:fs';
import path from 'node:path';
import prettier from 'prettier';
import { parse as parseYaml } from 'yaml';
import { loadRulePacks } from '../dist/engine/loader.js';
import { ruleAutomatability } from '../dist/engine/automatability.js';

const ROOT = process.cwd();
const INVENTORY = path.join(ROOT, 'rules/catalogues/asvs-5.0-controls.yaml');
const RULES_DIR = path.join(ROOT, 'rules');
const OUT_MD = path.join(ROOT, 'docs/reference/asvs-coverage.md');
const OUT_SNAPSHOT = path.join(ROOT, 'tests/fixtures/asvs-coverage-snapshot.json');

function loadInventory() {
  const doc = parseYaml(fs.readFileSync(INVENTORY, 'utf8'));
  return { version: String(doc.asvs_version), controls: doc.controls };
}

function citedBy() {
  const { packs } = loadRulePacks(RULES_DIR);
  const map = new Map();
  for (const pack of packs) {
    for (const rule of pack.rules ?? []) {
      for (const ref of rule.references ?? []) {
        const m = /^ASVS-([\d.]+)$/.exec(ref);
        if (!m) continue;
        if (!map.has(m[1])) map.set(m[1], []);
        map.get(m[1]).push({ id: rule.id, auto: ruleAutomatability(rule) });
      }
    }
  }
  return map;
}

function renderMd(version, controls, cited) {
  const covered = controls.filter((c) => cited.has(c.id));
  const lines = [];
  lines.push('# ASVS coverage map');
  lines.push('');
  lines.push('<!-- GENERATED by scripts/gen-asvs-coverage.mjs — do not hand-edit. -->');
  lines.push('');
  lines.push(
    `Join of the vendored OWASP ASVS ${version} control inventory against every ` +
      '`ASVS-*` reference cited by the rule packs. A control listed with rules ' +
      'is *claimed*, not proven: the cited rule pattern-matches the shape, it ' +
      'does not verify the control. Controls nobody cites are **unassessed** — ' +
      'neither covered nor uncoverable; partial/uncoverable triage is future work.',
  );
  lines.push('');
  lines.push(
    `Covered: **${covered.length} of ${controls.length} controls** ` +
      `(${Math.round((100 * covered.length) / controls.length)}%).`,
  );
  lines.push('');
  const chapters = [...new Set(controls.map((c) => c.chapter))].sort();
  for (const ch of chapters) {
    const rows = controls.filter((c) => c.chapter === ch);
    const hit = rows.filter((c) => cited.has(c.id)).length;
    lines.push(`## ${ch} — ${hit}/${rows.length} covered`);
    lines.push('');
    lines.push('| Control | Requirement | Covering rules |');
    lines.push('| ------- | ----------- | -------------- |');
    for (const c of rows) {
      const cover = cited.get(c.id);
      const cell = cover ? cover.map((r) => `${r.id} (${r.auto})`).join(', ') : '*unassessed*';
      const title = c.title.length > 110 ? `${c.title.slice(0, 110)}…` : c.title;
      lines.push(`| ${c.id} (L${c.level}) | ${title} | ${cell} |`);
    }
    lines.push('');
  }
  return `${lines.join('\n').trimEnd()}\n`;
}

function snapshot(cited) {
  return `${JSON.stringify({ covered: [...cited.keys()].sort() }, null, 2)}\n`;
}

const check = process.argv.includes('--check');
const { version, controls } = loadInventory();
const cited = citedBy();
const md = renderMd(version, controls, cited);
const snap = snapshot(cited);
if (check) {
  const stale = [];
  const wantMd = await prettier.format(md, { filepath: OUT_MD });
  if (!fs.existsSync(OUT_MD) || fs.readFileSync(OUT_MD, 'utf8') !== wantMd) stale.push(OUT_MD);
  if (!fs.existsSync(OUT_SNAPSHOT) || fs.readFileSync(OUT_SNAPSHOT, 'utf8') !== snap) {
    stale.push(OUT_SNAPSHOT);
  }
  if (stale.length > 0) {
    console.error(`gen-asvs-coverage: stale: ${stale.join(', ')} — run without --check.`);
    process.exit(1);
  }
} else {
  // The --check gate compares bytes and prettier owns markdown table
  // padding, so both modes go through the same formatted form: write
  // raw, format the file, and compare against the formatted bytes.
  // (Comparing raw output against the committed file can never pass —
  // that exact bug shipped in the first version of this script.)
  fs.writeFileSync(OUT_MD, md);
  fs.writeFileSync(OUT_SNAPSHOT, snap);
  const formatted = await prettier.format(md, { filepath: OUT_MD });
  fs.writeFileSync(OUT_MD, formatted);
  const formattedSnap = await prettier.format(snap, { filepath: OUT_SNAPSHOT });
  fs.writeFileSync(OUT_SNAPSHOT, formattedSnap);
  console.log(`wrote ${OUT_MD} (${controls.length} controls, ${cited.size} covered)`);
  console.log(`wrote ${OUT_SNAPSHOT}`);
}
